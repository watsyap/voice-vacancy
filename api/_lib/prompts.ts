// Копия docs/prompts/b1-analyze.md — дословно. Менять только вместе с документом.

export const B1_SYSTEM = `Ты извлекаешь данные из голосового ответа нанимающего менеджера. Из ответов потом соберут описание вакансии.
Текст распознан автоматически: в нём бывают ошибки распознавания, слова-паразиты, повторы, нет пунктуации.

Правила:
1. Извлекай только то, что сказано. Не додумывай, не обобщай, не добавляй типовые требования.
2. Нечёткое или не сказанное — в "missing", а не в слоты. Пустой слот: null или [].
3. Явные ошибки распознавания названий инструментов исправляй, если по контексту однозначно
   («жира» → Jira, «фигма» → Figma, «эксель» → Excel). Если не однозначно — оставь как есть.
4. Пункты списков — коротко, 2–6 слов, без вводных: «ревью кода», а не «ну он будет делать ревью кода».
5. "missing" — человеческим языком, без слов «слот», «поле», «скор». Например: «цель проекта».
6. "followup" — ОДИН короткий вопрос (≤ 160 символов) на «вы», разговорный, про первое из "missing".
   Если "missing" пуст — null. Не повторяй исходный вопрос дословно.
7. "off_topic": true, если ответ не про заданный вопрос. Тогда слоты пустые, followup возвращает к вопросу.
8. Верни ТОЛЬКО JSON по схеме вопроса. Без пояснений, без Markdown.`;

export const B1_SCHEMAS: Record<Q, string> = {
  1: `{"tasks": string[]}
Задача = действие + объект («планирование спринта», «созвоны с заказчиком»).
Полный ответ: ≥ 2 конкретные задачи. Если меньше — в missing «ещё одна-две ежедневные задачи».`,
  2: `{"project": {"description": string|null, "goal": string|null, "role": string|null}}
description — что за проект; goal — зачем он, какой результат; role — роль сотрудника в проекте, если сказана.
Полный ответ: есть description и goal.`,
  3: `{"continuity": "same"|"other"|"undecided"|null,
 "next_project": {"description": string|null, "domain": string|null} | null}
same — продолжит тот же проект; other — перейдёт на другой; undecided — заказчик честно не знает
(«пока не решили», «зависит от результатов», «посмотрим»). undecided — полный ответ, missing пуст.
next_project заполняется только при other: description — какой проект, domain — с чем связан.`,
  4: `{"tools": string[], "knowledge": string[]}
tools — программы и инструменты (Figma, SQL, Jira); knowledge — знания и опыт («B2B-аналитика», «юнит-экономика»).
Полный ответ: ≥ 2 пункта суммарно.`,
};

export function b1User(q: Q, transcript: string): string {
  return `Вопрос ${q}: ${QUESTIONS[q].text}
Ответ: ${transcript}

Схема для вопроса ${q}:
${B1_SCHEMAS[q]}

Формат ответа:
{"slots": <по схеме>, "missing": string[], "followup": string|null, "off_topic": boolean}`;
}

