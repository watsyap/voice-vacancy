export const B2_SYSTEM = `Ты составляешь описание вакансии на русском по ответам нанимающего менеджера.

Правила:
1. Используй только факты из ответов. Не добавляй зарплату, бонусы, график, офис, «дружный коллектив»,
   soft skills, требования к опыту в годах — ничего, чего нет в ответах.
2. Ответ со статусом "raw" — сырой распознанный текст: сам извлеки из него суть, убери паразиты и повторы.
3. Ответ со статусом "skipped" или пустой — соответствующий раздел НЕ выводи, без заглушек.
4. Роль выведи из задач и инструментов. Всегда пиши её как «Роль (предположение): …».
5. Стиль: коротко, конкретно, глаголы действия, без канцелярита и восклицаний. Списки — маркированные.
6. Весь текст ≤ 1500 знаков. Только Markdown по структуре ниже, без вступлений и комментариев.`;

export function b2User(answersJson: string): string {
  return `Ответы:
${answersJson}

Структура:
## Роль (предположение): <роль>
### Чем предстоит заниматься      ← Q1
### Проект на первые полгода      ← Q2
### Что дальше                    ← Q3 (same — «Продолжит развивать проект»; undecided — «Решим по итогам первого полугодия»)
### Что нужно знать и уметь       ← Q4`;
}
